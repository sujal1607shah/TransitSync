const PDFDocument = require('pdfkit');
const fs = require('fs');
const path = require('path');

/**
 * Generate PDF Proof of Delivery document
 */
const generatePODPDF = async (podData, outputPath) => {
  return new Promise((resolve, reject) => {
    try {
      const doc = new PDFDocument({ margin: 40 });
      const writeStream = fs.createWriteStream(outputPath);

      doc.pipe(writeStream);

      // Header
      doc.fontSize(22).fillColor('#2563EB').text('TransitSync', { align: 'left' });
      doc.fontSize(10).fillColor('#64748B').text('Smart Fleet Management & Delivery System', { align: 'left' });
      doc.moveDown();

      doc.fontSize(16).fillColor('#0F172A').text('PROOF OF DELIVERY RECEIPT', { align: 'center', underline: true });
      doc.moveDown(1.5);

      // Metadata Box
      doc.fontSize(12).fillColor('#1E293B');
      doc.text(`POD ID: ${podData.podId}`);
      doc.text(`Trip ID: ${podData.tripID}`);
      doc.text(`Driver Name: ${podData.driverName || 'Alex Driver'}`);
      doc.text(`Receiver Name: ${podData.receiverName}`);
      doc.text(`Delivery Date: ${new Date(podData.deliveryDate || Date.now()).toLocaleString()}`);
      doc.text(`Delivery Location: ${podData.deliveryLocation || 'Client Destination Yard'}`);
      doc.text(`Notes: ${podData.deliveryNotes || 'Delivery completed in good condition.'}`);
      doc.moveDown();

      // Status Badge
      doc.fontSize(14).fillColor('#10B981').text(`Status: VERIFIED & CONFIRMED ✅`);
      doc.moveDown();

      // Footer
      doc.fontSize(9).fillColor('#94A3B8').text('Generated automatically by TransitSync Dispatch System', {
        align: 'center',
      });

      doc.end();

      writeStream.on('finish', () => resolve(outputPath));
      writeStream.on('error', (err) => reject(err));
    } catch (err) {
      reject(err);
    }
  });
};

/**
 * Generate PDF Expense Report document
 */
const generateExpensePDF = async (reportData, outputPath) => {
  return new Promise((resolve, reject) => {
    try {
      const doc = new PDFDocument({ margin: 36, size: 'A4' });
      const writeStream = fs.createWriteStream(outputPath);

      doc.pipe(writeStream);

      // --- Brand Header ---
      doc.rect(36, 36, doc.page.width - 72, 54).fill('#0F172A');
      doc.fontSize(20).fillColor('#38BDF8').text('TransitSync', 48, 48, { continued: true });
      doc.fontSize(11).fillColor('#94A3B8').text('  |  Enterprise Fleet Management & Logistics Statement');

      doc.fontSize(9).fillColor('#CBD5E1').text(
        `Generated: ${new Date(reportData.generatedAt || Date.now()).toLocaleString()}  •  Confidential`,
        48,
        70
      );

      doc.y = 105;

      // --- Title & Organization ---
      doc.fontSize(15).fillColor('#0F172A').text('EXPENSE & FUEL AUDIT STATEMENT', { align: 'left' });
      doc.fontSize(10).fillColor('#475569').text(
        `Organization: ${reportData.organizationName || 'TransitSync Org'} (${reportData.organizationCode || 'GLOBAL'})  |  Generated by: ${reportData.generatedByName || 'Admin'} [${reportData.generatedByRole || 'Admin'}]`
      );
      if (reportData.period) {
        doc.fontSize(9).fillColor('#64748B').text(`Period / Filter: ${reportData.period}`);
      }
      doc.moveDown(0.8);

      // --- Financial Summary Cards Box ---
      const metrics = reportData.metrics || {};
      const total = Number(metrics.totalExpense || 0);
      const fuel = Number(metrics.fuelExpense || 0);
      const maint = Number(metrics.maintenanceExpense || 0);
      const toll = Number(metrics.tollExpense || 0);
      const other = Number(metrics.otherExpense || 0);

      const boxY = doc.y;
      const boxW = (doc.page.width - 72 - 30) / 4;
      const cardHeight = 46;

      const cards = [
        { label: 'TOTAL EXPENDITURE', val: `Rs. ${total.toLocaleString('en-IN')}`, bg: '#EFF6FF', text: '#1E40AF', border: '#BFDBFE' },
        { label: 'FUEL CHARGES', val: `Rs. ${fuel.toLocaleString('en-IN')}`, bg: '#FEF3C7', text: '#B45309', border: '#FDE68A' },
        { label: 'MAINTENANCE', val: `Rs. ${maint.toLocaleString('en-IN')}`, bg: '#FEE2E2', text: '#B91C1C', border: '#FECACA' },
        { label: 'TOLLS & OTHER', val: `Rs. ${(toll + other).toLocaleString('en-IN')}`, bg: '#ECFDF5', text: '#047857', border: '#A7F3D0' },
      ];

      cards.forEach((card, idx) => {
        const x = 36 + idx * (boxW + 10);
        doc.rect(x, boxY, boxW, cardHeight).fillAndStroke(card.bg, card.border);
        doc.fontSize(7.5).fillColor(card.text).text(card.label, x + 6, boxY + 8, { width: boxW - 12 });
        doc.fontSize(12).fillColor(card.text).text(card.val, x + 6, boxY + 24, { width: boxW - 12 });
      });

      doc.y = boxY + cardHeight + 16;

      // --- Itemized Table Header ---
      doc.fontSize(11).fillColor('#0F172A').text(`Itemized Records (${(reportData.items || []).length} Transactions)`);
      doc.moveDown(0.4);

      const tableTop = doc.y;
      const colX = { date: 36, cat: 106, vehicle: 186, notes: 276, amount: doc.page.width - 36 - 80 };
      const colW = { date: 65, cat: 75, vehicle: 85, notes: 165, amount: 80 };

      // Table Header Row
      doc.rect(36, tableTop, doc.page.width - 72, 20).fill('#1E293B');
      doc.fontSize(8.5).fillColor('#FFFFFF');
      doc.text('Date', colX.date + 6, tableTop + 5, { width: colW.date });
      doc.text('Category', colX.cat, tableTop + 5, { width: colW.cat });
      doc.text('Vehicle / Trip', colX.vehicle, tableTop + 5, { width: colW.vehicle });
      doc.text('Description / Notes', colX.notes, tableTop + 5, { width: colW.notes });
      doc.text('Amount (INR)', colX.amount, tableTop + 5, { width: colW.amount, align: 'right' });

      let currentY = tableTop + 20;

      const items = reportData.items || [];
      if (items.length === 0) {
        doc.rect(36, currentY, doc.page.width - 72, 24).fill('#F8FAFC');
        doc.fontSize(9).fillColor('#64748B').text('No expense records logged for this period.', 48, currentY + 7);
        currentY += 24;
      } else {
        items.forEach((item, index) => {
          // Check for page break
          if (currentY > 740) {
            doc.addPage();
            currentY = 40;
            // Repeat table header on new page
            doc.rect(36, currentY, doc.page.width - 72, 20).fill('#1E293B');
            doc.fontSize(8.5).fillColor('#FFFFFF');
            doc.text('Date', colX.date + 6, currentY + 5, { width: colW.date });
            doc.text('Category', colX.cat, currentY + 5, { width: colW.cat });
            doc.text('Vehicle / Trip', colX.vehicle, currentY + 5, { width: colW.vehicle });
            doc.text('Description / Notes', colX.notes, currentY + 5, { width: colW.notes });
            doc.text('Amount (INR)', colX.amount, currentY + 5, { width: colW.amount, align: 'right' });
            currentY += 20;
          }

          const rowBg = index % 2 === 0 ? '#FFFFFF' : '#F8FAFC';
          const rowHeight = 22;
          doc.rect(36, currentY, doc.page.width - 72, rowHeight).fillAndStroke(rowBg, '#F1F5F9');

          const formattedDate = item.date ? String(item.date).split('T')[0] : '--';
          const cat = item.category || 'GENERAL';
          const veh = item.vehicleID || item.tripID || '--';
          const desc = (item.description || item.notes || '-').substring(0, 40);
          const amt = Number(item.amount || item.cost || 0);

          doc.fontSize(8).fillColor('#334155');
          doc.text(formattedDate, colX.date + 6, currentY + 6, { width: colW.date, lineBreak: false });
          doc.text(cat, colX.cat, currentY + 6, { width: colW.cat, lineBreak: false });
          doc.text(veh, colX.vehicle, currentY + 6, { width: colW.vehicle, lineBreak: false });
          doc.text(desc, colX.notes, currentY + 6, { width: colW.notes, lineBreak: false });
          doc.fontSize(8.5).fillColor('#0F172A').text(`Rs. ${amt.toLocaleString('en-IN')}`, colX.amount, currentY + 6, {
            width: colW.amount,
            align: 'right',
          });

          currentY += rowHeight;
        });
      }

      // --- Total Summary Row ---
      doc.rect(36, currentY, doc.page.width - 72, 22).fill('#E2E8F0');
      doc.fontSize(9).fillColor('#0F172A').text('GRAND TOTAL AUDITED EXPENSES', colX.date + 6, currentY + 6);
      doc.fontSize(9.5).fillColor('#1E40AF').text(`Rs. ${total.toLocaleString('en-IN')}`, colX.amount, currentY + 6, {
        width: colW.amount,
        align: 'right',
      });
      currentY += 34;

      // --- Verification & Signoff Footer ---
      if (currentY > 700) {
        doc.addPage();
        currentY = 40;
      }

      doc.rect(36, currentY, doc.page.width - 72, 45).fillAndStroke('#F8FAFC', '#E2E8F0');
      doc.fontSize(8).fillColor('#10B981').text('STATUS: VERIFIED & AUDITED STATEMENT', 48, currentY + 10);
      doc.fontSize(7.5).fillColor('#64748B').text(
        'This statement was automatically generated by TransitSync Dispatch & Fleet Accounting Engine. Any discrepancies must be reported to the Fleet Administrator.',
        48,
        currentY + 23,
        { width: doc.page.width - 96 }
      );

      doc.end();

      writeStream.on('finish', () => resolve(outputPath));
      writeStream.on('error', (err) => reject(err));
    } catch (err) {
      reject(err);
    }
  });
};

module.exports = { generatePODPDF, generateExpensePDF };

